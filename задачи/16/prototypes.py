# Импортируем декоратор для кэширования результатов функций
from functools import lru_cache

# Кэшируем результаты функции f
@lru_cache(None)
def f(n):
    # Если n меньше 31054, рекурсивно вызываем f с увеличенным на 4 аргументом
    # и прибавляем 3020 к результату
    if n < 31054:
        return f(n + 4) + 3020
    # Если n >= 31054, вычисляем значение через функцию g
    # 3 * (g(n-2) - 15)
    # return автоматически завершает выполнение функции, поэтому else не нужен
    return 3 * (g(n - 2) - 15)

# Кэшируем результаты функции g
@lru_cache(None)
def g(n):
    # Если n >= 28, рекурсивно вызываем g с уменьшенным на 5 аргументом
    # и вычитаем 15 из результата
    if n >= 28:
        return g(n - 5) - 15
    # Если n < 28, вычисляем значение по формуле 3*n - 4
    return 3 * n - 4

# Прогреваем кэш для функции g
# Вычисляем значения g для всех чисел от 0 до 399999
# Это нужно, чтобы при вызове f значения g уже были в кэше
for i in range(400000):
    g(i)

# Прогреваем кэш для функции f в обратном порядке
# Идем от больших значений к меньшим (от 399999 до 0)
# Это обеспечивает, что при вычислении f(15) все необходимые значения
# f для больших чисел уже будут в кэше
for i in reversed(range(400000)):
    f(i)

# Вычисляем и выводим значение f(15)
print(f(15))