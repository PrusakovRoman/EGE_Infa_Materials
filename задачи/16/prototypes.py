# Импортируем декоратор для кэширования результатов функции
from functools import lru_cache

# Применяем декоратор lru_cache для запоминания результатов функции
# None означает, что кэш будет неограниченного размера
@lru_cache(None)
def f(n):
    # Базовый случай рекурсии: если n равно 1, возвращаем 1
    if n == 1: 
        return 1
    # Рекурсивный случай: если n больше 1, 
    # возвращаем n, умноженное на результат функции от n-1
    elif n > 1:
        return n * f(n-1)

# Прогреваем кэш - вычисляем значения функции для всех чисел от 0 до 2024
# Это нужно, чтобы при вычислении нужного выражения значения уже были в кэше
for i in range(2025):
    f(i)

# Вычисляем и выводим результат выражения:
# (f(2024) - 2 * f(2023)) // f(2022)
# // - чтобы не оставалось десятичной части
print((f(2024) - 2 * f(2023)) // f(2022))

