# Под каким номером в списке стоит первое слово с нечётным номером, которое не начинается и не заканчивается буквой А и при этом содержит не менее трёх букв Л?

from itertools import product  # импортируем функцию для декартова произведения (комбинаторика)

n = 1  # счетчик номеров комбинаций (начинаем с 1)

# Генерируем все возможные 5-буквенные слова из букв 'АЕИЛНОПЦ'
# repeat=5 означает, что длина слова = 5 букв
for s in product('АЕИЛНОПЦ', repeat=5):
    s = ''.join(s)  # преобразуем кортеж символов в строку
    
    # Проверяем три условия:
    # 1. n % 2 != 0 - номер комбинации нечетный
    # 2. s[0] != 'А' - первая буква не 'А'
    # 3. s[-1] != 'А' - последняя буква не 'А'
    # 4. s.count('Л') >= 3 - в слове не менее 3 букв 'Л'
    if n % 2 != 0 and s[0] != 'А' and s[-1] != 'А' and s.count('Л') >= 3:
        print(n)  # выводим номер подходящей комбинации
        break  # прекращаем поиск после первого найденного
    
    n += 1  # увеличиваем счетчик для следующей комбинации

