# 4. Леонид составляет коды перестановкой букв слова ПАРИЖАНКА. При этом в этих кодах ровно один раз встречаются две идущие подряд гласные буквы. Сколько различных кодов может составить Леонид?

from itertools import permutations, product #permutations = перестановки
k = 0  # счетчик подходящих перестановок

# Генерируем все возможные двухбуквенные сочетания из букв 'ИА' (ИИ, ИА, АИ, АА)
combs = [''.join(c) for c in product('ИА', repeat=2)]

# Генерируем все возможные трехбуквенные сочетания из букв 'ИА' (ИИИ, ИИА, ИАИ, АИИ, ИАА, АИА, ААИ, ААА)
combs1 = [''.join(c) for c in product('ИА', repeat=3)]

# Генерируем все уникальные перестановки букв слова 'ПАРИЖАНКА'
# set() убирает дубликаты, т.к. в слове есть повторяющиеся буквы (А встречается 3 раза)
for s in set(permutations('ПАРИЖАНКА', len('ПАРИЖАНКА'))):
    s = ''.join(s)  # преобразуем кортеж символов в строку
    
    # Проверяем условия:
    # 1. Ровно одна двухбуквенная комбинация из ИА встречается в строке
    # 2. Ни одной трехбуквенной комбинации из ИА нет в строке
    if sum([1 for c in combs if c in s]) == 1 and all(c not in s for c in combs1):
        k += 1  # увеличиваем счетчик, если условия выполнены

print(k)  # выводим количество подходящих перестановок

