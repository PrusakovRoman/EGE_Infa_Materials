# 5. Леонид составляет коды перестановкой букв слова СОРТИРОВКА. При этом в кодах никакие три согласные или три гласные буквы не должны стоять рядом. Сколько различных кодов может составить Леонид?

from itertools import permutations, product

k = 0  # счетчик подходящих перестановок

# Генерируем все возможные трехбуквенные комбинации из гласных букв 'ОИА'
combs1 = [''.join(c) for c in product('ОИА', repeat=3)]

# Генерируем все возможные трехбуквенные комбинации из согласных букв 'СРТВК'
combs2 = [''.join(c) for c in product('СРТВК', repeat=3)]

# Генерируем все уникальные перестановки букв слова 'СОРТИРОВКА'
# set() убирает дубликаты, так как в слове есть повторяющиеся буквы (О, Р)
for s in set(permutations('СОРТИРОВКА', len('СОРТИРОВКА'))):
    s = ''.join(s)  # преобразуем кортеж символов в строку
    
    # Проверяем два условия:
    # 1. all(c not in s for c in combs1) - нет ни одной тройки подряд идущих гласных (О,И,А)
    # 2. all(c not in s for c in combs2) - нет ни одной тройки подряд идущих согласных (С,Р,Т,В,К)
    if all(c not in s for c in combs1) and all(c not in s for c in combs2):
        k += 1  # увеличиваем счетчик, если оба условия выполнены

print(k)  # выводим количество подходящих перестановок

