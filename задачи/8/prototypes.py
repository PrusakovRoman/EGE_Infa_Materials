# 2. Сколько существует чисел, тринадцатеричная запись которых содержит шесть цифр, причем среди них по крайней мере две цифры 0 и ровно две цифры с числовым значением, превышающим 9, причём стоящие рядом.

from itertools import product  # импортируем функцию для генерации комбинаций

k = 0  # счетчик подходящих комбинаций

# Генерируем все возможные двухбуквенные комбинации из букв 'ABC'
# Нужны для проверки наличия хотя бы одной такой пары в числе
combs = [''.join(c) for c in product('ABC', repeat=2)]

# Генерируем все 6-значные комбинации из цифр 0-9 и букв A,B,C
for s in product('0123456789ABC', repeat=6):
    s = ''.join(s)  # преобразуем кортеж символов в строку
    
    # Проверяем условия:
    # 1. s[0] != '0' - первая цифра не ноль (число не начинается с нуля)
    if s[0] != '0':
        # 2. s.count('0') >= 2 - в числе не менее двух нулей
        # 3. sum([1 for el in s if el in 'ABC']) == 2 - ровно две буквы (из ABC)
        # 4. any(c in s for c in combs) - есть хотя бы одна пара букв подряд
        if s.count('0') >= 2 and sum([1 for el in s if el in 'ABC']) == 2 and any(c in s for c in combs):
            k += 1  # увеличиваем счетчик, если все условия выполнены

print(k)  # выводим количество подходящих чисел

