# ТОЛЬКО ДЕЛИТЕЛИ, ВЫБОР ПРОСТЫХ

# Пусть M – сумма минимального и максимального простых натуральных делителей целого числа, не считая самого числа. Если таких делителей у числа нет, то значение M считается равным нулю.

# Напишите программу, которая перебирает целые числа, бо́льшие 5 700 000, в порядке возрастания и ищет среди них такие, для которых M больше 70 000 и является полным квадратом натурального числа. В ответе запишите в первом столбце таблицы первые пять найденных чисел в порядке возрастания, а во втором столбце – соответствующие им значения M.

# Например, для числа 14 М = 2 + 7 = 9.

# Количество строк в таблице для ответа избыточно.

def prost(x):
    return all(x % d != 0 for d in range(2, int(x**.5)+1))

def count_M(x):
    a = set()
    for d in range(2, int(x**.5)+1): #пропускаем единицу и само число, так сказано в задаче. И единица не простое число!!!
        if x % d == 0:
            if prost(d): #если в задаче не просят простые, то и эта проверка не нужна
                a.add(d)
            if prost(x//d):
                a.add(x//d)
    if len(a) == 0: return 0
    return min(a) + max(a)

k = 0 #для отсчета первых пяти. Можно не считать, но на ЕГЭ комп может взорваться

for n in range(5_700_000+1, 10**10):
    M = count_M(n)
    if M > 70000 and M**0.5 == round(M**0.5):
        k += 1
        if k > 5: break
        print(n, M)

