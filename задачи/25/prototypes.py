# 1. ТОЛЬКО МАСКА + ЧИСЛО КРАТНО

# Назовём маской числа последовательность цифр, в которой также могут встречаться следующие символы:
# – символ «?» означает ровно одну произвольную цифру;
# – символ «*» означает любую последовательность цифр произвольной длины; в том числе «*» может задавать
# и пустую последовательность.
# Например, маске 123*4?5 соответствуют числа 123405 и 12300405.
# Среди натуральных чисел, не превышающих 10**10, найдите все числа, соответствующие маске 89*6?7?9?, делящиеся на 9874 без остатка.
# В ответе запишите в первом столбце таблицы все найденные числа в порядке возрастания, а во втором столбце – соответствующие им результаты деления этих чисел на 9874.
# Количество строк в таблице для ответа избыточно. 

from re import *
# Про re читай здесь: https://habr.com/ru/articles/349860/ , а именно таблица "Шаблоны, соответствующие одному символу". Используем re вместо fnmatch, так как первый более гибкий и используется в реальной разработке.
for n in range(9874, 10**10, 9874):
    pat = r'89[0-9]{0,}6[0-9]7[0-9]9[0-9]'
    if fullmatch(pat, str(n)):
        print(n, n//9874)

