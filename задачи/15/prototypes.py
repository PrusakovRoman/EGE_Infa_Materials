# Определяем функцию f с параметрами x и a
# Функция проверяет выполнение логического условия для конкретного x при данном a
def f(x, a):
    # Возвращаем результат логического выражения:
    # (x%25==0) <= ((x%a!=0) <= (x%60!=0))
    return (x%25==0) <= ((x%a!=0) <= (x%60!=0))

# Перебираем возможные значения a от 1 до 999
for a in range(1, 1000):
    # all(условие for x in range(1, 1000)) - проверяет, что условие выполняется
    # для ВСЕХ x от 1 до 999 (для всех натуральных x до 1000)
    #
    # f(x,a) - проверяет выполнение нашего условия для конкретных x и a
    # all(f(x,a) for x in range(1, 1000)) - истинно, если условие верно для всех x
    if all(f(x, a) for x in range(1, 1000)):
        # Если для данного a условие выполняется для всех x,
        # выводим это a на экран
        print(a)

