def f(x, a1, a2):
    A = [n for n in range(a1,a2+1)]
    B = [n for n in range(22, 41)]
    C = [n for n in range(32, 51)]
    return (not(x in A)) <= ((x in B) == (x in C))
ans = 100000000000000000
