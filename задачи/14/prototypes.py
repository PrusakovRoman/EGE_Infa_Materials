# 4. Операнды арифметического выражения записаны в системе счисления с основанием 40.

# 871x291 + 366x631 + 973x618

# В записи чисел переменной x обозначена неизвестная цифра из алфавита 40-ричной системы счисления. Определите наименьшее значение x, при котором значение данного арифметического выражения кратно 39. Для найденного x вычислите частное от деления значения арифметического выражения на 13 и укажите его в ответе в десятичной системе счисления. Основание системы счисления указывать не нужно.


# Функция для перевода числа из любой системы счисления в десятичную
# num - список цифр числа (каждая цифра уже представлена числом от 0 до sys-1)
# sys - основание системы счисления
def conv_to_dec(num, sys):
    res = 0  # переменная для накопления результата
    
    # Проходим по всем цифрам числа слева направо
    for i in range(len(num)):
        # num[i] - текущая цифра
        # (len(num)-i-1) - степень, в которую нужно возвести основание
        res += num[i] * (sys ** (len(num)-i-1))
    
    return res  # возвращаем полученное десятичное число

# Перебираем все возможные значения x от 0 до 39
# (так как основание системы 40, цифры могут быть от 0 до 39)
