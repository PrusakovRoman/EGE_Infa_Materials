# 3. Операнды арифметического выражения записаны в системе счисления с некоторым основанием p 22A12E p + 2F1391 p − 1H05D0 p. Определите наименьшее возможное основание системы счисления, при котором значение данного арифметического выражения кратно 19. Для найденной системы счисления p вычислите частное от деления значения арифметического выражения на 19 и укажите его в ответе в десятичной системе счисления. Основание системы счисления указывать не нужно.

# Перебираем возможные основания системы счисления от 18 до 36
for p in range(18, 37):
    # Переводим числа из системы с основанием p в десятичную и выполняем действия
    # '22A12E' + '2F1391' - '1H05D0' (все числа в системе с основанием p)
    n = int('22A12E', p) + int('2F1391', p) - int('1H05D0', p)
    
    # Проверяем, делится ли результат на 19 без остатка
    if n % 19 == 0:
        # Если да - выводим результат деления на 19
        print(n // 19)
        break  # прекращаем поиск после первого подходящего основания