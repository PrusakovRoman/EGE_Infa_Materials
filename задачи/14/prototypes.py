# 2. Значение арифметического выражения 3*27^9 + 2*27^6 + 27^3 - x,  где х - целое положительное число, не превышающее 27 000, записали в 27-ричной системе счисления. Определите наименьшее значение х, при котором в 27-ричной записи числа, являющегося значением данного арифметического выражения, содержится ровно 6 нулей.
# В ответе запишите число в десятичной системе счисления.

# Перебираем возможные значения x от 1 до 27000 включительно
for x in range(1, 27000+1):
    # Вычисляем значение выражения для текущего x
    # 3*27^9 + 2*27^6 + 27^3 - x
    n = 3*27**9 + 2*27**6 + 27**3 - x
    
    # Переводим полученное число в 27-ричную систему счисления
    new_n = conv_sys(n, 27)
    
    # Проверяем, содержит ли 27-ричная запись ровно 6 нулей
    if new_n.count('0') == 6:
        # Если да - выводим x и завершаем поиск
        print(x)
        break  # так как нужно наименьшее значение

