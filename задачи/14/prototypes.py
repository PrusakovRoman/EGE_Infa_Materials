# 2. Значение арифметического выражения 3*27^9 + 2*27^6 + 27^3 - x,  где х - целое положительное число, не превышающее 27 000, записали в 27-ричной системе счисления. Определите наименьшее значение х, при котором в 27-ричной записи числа, являющегося значением данного арифметического выражения, содержится ровно 6 нулей.
