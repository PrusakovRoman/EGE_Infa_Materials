# 1. Значение арифметического выражения  64^678 + 55^123 - x,
# где х – натуральное число, не превышающее 231, записали в 25-ричной системе счисления.
# Определите максимальное количество нулей в 25-ричной записи числа, являющегося значением данного арифметического выражения. В ответе запишите только целое число.


import string  # импортируем модуль для работы со строками и символами

# Функция перевода числа в другую систему счисления
def conv_sys(x, sys):
    # создаем строку из цифр и заглавных букв (для систем до 36)
    alph = string.digits + string.ascii_uppercase  # '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ' ( можно заполнять руками, главное не ошибиться :) )
    a = []
    while x:  # пока число не станет равным 0
        a.insert(0, alph[x%sys])  # находим остаток от деления (цифру) и добавляем в начало
        x//=sys  # целочисленно делим число на основание системы
    return ''.join(a)  # объединяем список в строку

ans = 0  # переменная для хранения максимального количества нулей

# Перебираем x от 0 до 231 (232 числа)
for x in range(232):
    n = 64**678 + 55**123 - x
    new_n = conv_sys(n, 25)  # переводим результат в 25-ричную систему
    # считаем количество нулей в записи и обновляем максимум
    ans = max(ans, new_n.count('0'))

print(ans)  # выводим результат

