# В файле содержится последовательность целых чисел. Её элементы могут принимать целые значения от -100 000 до 100 000 включительно. Определите количество троек элементов последовательности, в которых не более двух из трёх элементов являются четырёхзначными числами, а сумма элементов тройки не больше максимального элемента последовательности, оканчивающегося на 25. В ответе запишите количество найденных троек чисел, затем максимальную из сумм элементов таких троек.
# В данной задаче под тройкой подразумевается три идущих подряд элемента последовательности.

# Открываем файл с данными
# Путь: 'задачи/17/17_23276.txt'
f = open('задачи/17/17_23276.txt')

# Читаем все строки из файла, преобразуем в целые числа
# Получаем список a, содержащий все числа из файла
a = [int(n) for n in f.readlines()]

# Создаем пустой список для хранения подходящих сумм
ans = []

# Находим максимальное число, оканчивающееся на 25
# abs(n) % 100 == 25 - проверяем, что последние две цифры числа равны 25
# abs(n) берется для корректной работы с отрицательными числами
# Пример: -125 -> abs = 125 -> 125 % 100 = 25 -> условие выполняется
ma25 = max([n for n in a if abs(n) % 100 == 25])

# Проходим по списку, начиная с третьего элемента (индекс 2)
# Рассматриваем тройки соседних чисел: (a[i-2], a[i-1], a[i])
for i in range(2, len(a)):
    x = a[i-2]  # первый элемент тройки
    y = a[i-1]  # второй элемент тройки
    z = a[i]    # третий элемент тройки
    
    # Формируем список из трех чисел для удобства
    t = [x, y, z]
    
    # Первое условие: количество ЧЕТЫРЕХЗНАЧНЫХ чисел в тройке <= 2
    # len(str(abs(n))) == 4 - проверяем, что число четырехзначное
    # abs(n) берется для отрицательных чисел (например, -1234 имеет 4 цифры)
    # Генератор списка отбирает четырехзначные числа, len() считает их количество
    # Условие <= 2 означает, что в тройке может быть 0, 1 или 2 четырехзначных числа
    # (то есть не может быть ровно 3 четырехзначных числа)
    if len([n for n in t if len(str(abs(n))) == 4]) <= 2:
        
        # Второе условие: сумма элементов тройки не превышает ma25
        # Сравниваем сумму трех чисел с максимальным числом, оканчивающимся на 25
        if sum(t) <= ma25:
            ans.append(sum(t))  # добавляем подходящую сумму в список ans

# Выводим результат:
# len(ans) - количество найденных троек
# max(ans) - максимальную сумму среди подходящих троек
print(len(ans), max(ans))

