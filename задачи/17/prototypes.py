# В файле содержится последовательность натуральных чисел. Её элементы могут принимать целые значения от 1 до 100 000 включительно. Определите количество пар последовательности, в которых только один из элементов является двузначным числом, а сумма элементов пары кратна минимальному двузначному элементу последовательности. В ответе запишите количество найденных пар, затем максимальную из сумм элементов таких пар. В данной задаче под парой подразумевается два идущих подряд элемента последовательности. 

# Открываем файл с данными. Путь к файлу: 'задачи/17/17_23757.txt'
f = open('задачи/17/17_23757.txt')

# Читаем все строки из файла, преобразуем каждую в целое число
# Получаем список a, содержащий все числа из файла
a = [int(n) for n in f.readlines()]

# Создаем пустой список для хранения подходящих сумм
ans = []

# Находим минимальное двузначное число (от 10 до 99) в списке a
# Генератор списка отбирает только двузначные числа, затем min находит среди них наименьшее
mi = min([n for n in a if 10 <= n <= 99])

# Проходим по списку, начиная со второго элемента (индекс 1)
# Используем скользящее окно: рассматриваем пары соседних элементов (x, y)
for i in range(1, len(a)):
    x = a[i-1]  # предыдущий элемент
    y = a[i]    # текущий элемент
    
    # Проверяем условие: РОВНО одно из чисел является двузначным
    # Оператор ^ (XOR) возвращает True, если условия различны
    # Т.е. если x - двузначное, а y - нет, ИЛИ наоборот
    if (10 <= x <= 99) ^ (10 <= y <= 99):
        
        # Проверяем второе условие: сумма пары делится на минимальное двузначное число mi
        if (x + y) % mi == 0:
            ans.append(x + y)  # добавляем подходящую сумму в список ans

# Выводим результат:
# len(ans) - количество найденных пар
# max(ans) - максимальную сумму среди подходящих пар
print(len(ans), max(ans))

