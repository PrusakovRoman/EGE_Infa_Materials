# В файле электронной таблицы в каждой строке записаны семь целых чисел. Определите наибольшее повторяющееся число в строке таблице с наименьшим номером, для которой выполнены оба условия:
# – в строке два разных числа повторяются трижды, одно число не повторяется;
# – неповторяющееся число не больше минимального из повторяющихся чисел строки.
# В ответе запишите абсолютное значение полученного результата.

f = open('задачи/9/91.csv')

# Построчно читаем файл
for s in f.readlines():
    # Разбиваем строку по запятым и преобразуем каждое значение в целое число
    # Получаем список a из 6 чисел, в каждой строке 6 чисел)
    a = [int(n) for n in s.split(',')]
    
    # Создаем списки для чисел:
    # reps - числа, встречающиеся 3 раза (повторяющиеся)
    # noreps - числа, встречающиеся 1 раз (уникальные)
    reps = []
    noreps = []
    
    # Анализируем каждое число в строке
    for n in a:
        if a.count(n) == 1:
            # Если число встречается в списке ровно 1 раз
            noreps.append(n)
        elif a.count(n) == 3:
            # Если число встречается в списке ровно 3 раза
            reps.append(n)
        # Если число встречается 2, 4, 5 и т.д. раз - игнорируем
    
    # Проверяем условия для строки:
    # 1. Уникальных чисел должно быть ровно 1 (len(noreps) == 1)
    # 2. Повторяющихся чисел должно быть ровно 2 различных значения (len(set(reps)) == 2)
    if len(noreps) == 1 and len(set(reps)) == 2:
        
        # Проверяем, что уникальное число не превышает минимальное из повторяющихся
        # noreps[0] - единственное уникальное число
        # min(set(reps)) - минимальное среди повторяющихся чисел
        if noreps[0] <= min(set(reps)):
            # Если условие выполняется, выводим максимальное среди повторяющихся чисел
            print(max(reps))
            break  # Прерываем цикл после нахождения первой подходящей строки

