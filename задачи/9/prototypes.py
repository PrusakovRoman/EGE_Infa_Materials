# Откройте файл электронной таблицы, содержащей в каждой строке восемь натуральных чисел. Определите количество строк таблицы, содержащих числа, для которых выполнены оба условия:
# – в строке максимальное число встречается три или четыре раза, остальные числа без повторений;
# – сумма минимального и максимального из неповторяющихся чисел не больше суммы других неповторяющихся.
# В ответе запишите только число.

f = open('задачи/9/92.csv')

# Счетчик количества строк, удовлетворяющих условиям
ans = 0

# Построчно читаем файл
for s in f.readlines():
    # Разбиваем строку по запятым, преобразуем в целые числа
    # В каждой строке 8 чисел (по условию задачи)
    a = [int(n) for n in s.split(',')]
    
    # Находим максимальное число в строке
    ma = max(a)
    
    # Первое условие: проверяем структуру распределения чисел
    # Вариант 1: максимальное число встречается ровно 3 раза, 
    #           и всего в строке 6 различных чисел
    #           (8 чисел: 3 повтора максимума + 5 уникальных чисел = 6 различных чисел)
    # Вариант 2: максимальное число встречается ровно 4 раза,
    #           и всего в строке 5 различных чисел
    #           (8 чисел: 4 повтора максимума + 4 уникальных числа = 5 различных чисел,
    #            т.к. 4 уникальных числа + максимум = 5 различных чисел)
    if (a.count(ma) == 3 and len(set(a)) == 6) or (a.count(ma) == 4 and len(set(a)) == 5):
        
        # Находим числа, которые встречаются ровно 1 раз (уникальные)
        noreps = [n for n in a if a.count(n) == 1]
        
        # Сортируем уникальные числа по возрастанию
        noreps.sort()
        
        # Второе условие: проверяем, что сумма наименьшего и наибольшего
        # уникальных чисел не превышает сумму всех остальных уникальных чисел
        # noreps[1:-1] - срез от второго до предпоследнего элемента
        # Для варианта 1: уникальных чисел 5, условие: a + e <= b + c + d
        # Для варианта 2: уникальных чисел 4, условие: a + d <= b + c
        if (noreps[0] + noreps[-1]) <= sum(noreps[1:-1]):
            ans += 1  # Увеличиваем счетчик подходящих строк

# Выводим количество строк, удовлетворяющих всем условиям
print(ans)