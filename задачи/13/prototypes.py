# Создаем сеть с IP-адресом 162.198.0.157 и маской 255.255.255.224
# Параметр 0 отключает проверку на то, что 157 - это адрес сети
net = ip_network('162.198.0.157/255.255.255.224', 0)

# int(ip_address('162.198.0.157')) - преобразует IP-адрес в целое число
# int(net.network_address) - преобразует адрес сети в целое число
