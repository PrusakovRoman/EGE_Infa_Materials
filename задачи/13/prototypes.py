# 3. В терминологии сетей TCP/IP маской сети называют двоичное число, которое показывает, какая часть IP-адреса узла сети относится к адресу сети, а какая – к адресу узла в этой сети. Адрес сети получается в результате применения поразрядной конъюнкции к заданному адресу узла и его маске.
# Широковещательным адресом называется специализированный адрес, в котором на месте нулей в маске стоят единицы. Адрес сети и широковещательный адрес не могут быть использованы для адресации сетевых устройств.
# Сеть задана IP-адресом одного из входящих в неё узлов 98.71.254.171 и сетевой маской 255.248.0.0.
# Найдите наименьший в данной сети IP-адрес, содержащий в своей двоичной записи кратное 7 количество единиц, который может быть назначен компьютеру. В ответе укажите найденный IP-адрес без разделителей.
# Например, если бы найденный адрес был равен 111.22.3.44, то в ответе следовало бы записать 11122344.

from ipaddress import *  # импортируем модуль для работы с IP-адресами

# Создаем сеть с IP-адресом 98.71.254.171 и маской 255.248.0.0
net = ip_network('98.71.254.171/255.248.0.0', 0)

# Перебираем все IP-адреса в данной сети (от первого до последнего)
for ip in net:
    # Преобразуем IP-адрес в целое число, затем в двоичную строку
    # [2:] - отбрасываем префикс '0b'
    # zfill(32) - дополняем слева нулями до 32 бит (полный IP-адрес)
    b = bin(int(ip))[2:].zfill(32)
    
    # Проверяем, делится ли количество единиц в двоичной записи на 7 без остатка
    if b.count('1') % 7 == 0:
        # Если условие выполняется, выводим IP-адрес и завершаем поиск
        print(ip)
        break  # находим первый подходящий адрес

