# 1. 
# На вход алгоритма подаётся натуральное число N. Алгоритм строит по нему новое число R следующим образом.
# 1 Строится двоичная запись числа N.
# 2 Далее эта запись обрабатывается по следующему правилу:
# а) если число N делится на 5, то к этой записи дописывается справа две единицы;
# б) если число N на 5 не делится, то результат целочисленного деления N на 5 переводится в двоичную систему счисления и дописывается в конец числа. Полученная таким образом запись является двоичной записью искомого числа R.
# 3 Результат переводится в десятичную систему и выводится на экран.
# Например, для исходного числа 20 = 101002 результатом является число 10100112 = 83, а для исходного числа 14 = 11102 результатом является число 1110102 = 58
# Укажите минимальное чётное число N, для которого с помощью описанного алгоритма получается число, превышающее 896 В ответе запишите это число в десятичной системе счисления.

# Перебираем числа от 1 до 999
for n in range(1, 1000):
    # Получаем двоичную запись числа n (отбрасываем префикс '0b')
    s = bin(n)[2:]
    
    # Если число делится на 5 без остатка
    if n % 5 == 0:
        s += '11'  # дописываем '11' в конец двоичной записи
    else:
        # Иначе дописываем двоичную запись целой части от деления на 5
        s += bin(n//5)[2:]
    
    # Преобразуем полученную двоичную строку обратно в десятичное число
    r = int(s, 2)
    
    # Здесь всегда проверяешь работу программы на примерах, которые даны в условии!!!
    # Если r больше 896 и n четное
    if r > 896 and n % 2 == 0:
        print(n)  # выводим найденное число
        break      # прекращаем поиск после первого найденного


# --------------------- ПОИСК R (ситуация аналогична)

# 2.
# На вход алгоритма подаётся натуральное число N. Алгоритм строит по нему новое число R следующим образом.

# 1. Строится троичная запись числа N.
# 2. Далее эта запись обрабатывается по следующему правилу:
# а) если сумма цифр троичной записи числа кратна 9, то к этой записи справа дописывается 2
# б) если сумма цифр троичной записи числа не кратна 9, то к этой записи справа дописывается троичная запись остатка от деления суммы цифр записи на 9;
# Полученная таким образом запись является троичной записью искомого числа R.
# 3. Результат переводится в десятичную систему и выводится на экран.

# Например, для исходного числа 9 = 1003 результатом является число 10013 = 28. А для исходного числа 161 = 122223 результатом является число 1222223 = 485

# Укажите минимальное число R, которое может быть результатом работы данного алгоритма, при условии, что N больше 166.
# В ответе запишите это число в десятичной системе счисления.


# Функция для перевода числа в систему счисления с заданным основанием
def conv_sys(n, sys): #пояснение по функции перевода в utils.py
    a = []
    while n:  # пока число не равно 0
        a.insert(0, str(n%sys))  # находим остаток от деления и добавляем в начало
        n //= sys  # целочисленно делим на основание
    return ''.join(a)  # объединяем цифры в строку

ans = 10**9  # начальное значение для поиска минимума (очень большое число)

# Перебираем числа от 167 до 999
for n in range(167, 1000):
    # Переводим n в троичную систему
    s = conv_sys(n, 3) #Если просят перевести не в 2-ю,8-ю,16-ю, то пишем функцию перевода сами
    
    # Считаем сумму цифр в троичной записи
    summa = sum(map(int, s))
    
    # Если сумма цифр делится на 9
    if summa % 9 == 0:
        s += '2'  # дописываем '2' в конец
    else:
        # Иначе дописываем остаток от деления суммы на 9 в троичной системе
        s += conv_sys(summa % 9, 3)
    
    # Переводим полученную троичную строку обратно в десятичное число
    r = int(s, 3)
    
    # Обновляем минимальное значение
    ans = min(ans, r)

print(ans)  # выводим результат