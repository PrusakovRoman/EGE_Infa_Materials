# Исполнитель преобразует число на экране. У исполнителя есть две команды, которые обозначены латинскими буквами:
# A. Вычти 1
# B. Найди целую часть от деления на 2
# Первая из них уменьшает число на экране на 1, вторая заменяет число на экране на целую части от деления числа на 2. Программа для исполнителя - это последовательность команд.
# Сколько существует программ, для которых при исходном числе 40 результатом является 6, и при этом траектория вычислений содержит число 16?

def f(a, b):
    # Базовый случай: если достигли целевого числа, возвращаем 1 (найден путь)
    if a == b:
        return 1
    # Если текущее число меньше целевого, дальше уменьшать нельзя
    # возвращаем 0 (путь не найден)
    elif a < b:
        return 0
    # Рекурсивно считаем количество путей:
    # 1. Вычитаем 1 из числа a: f(a-1, b)
    # 2. Делим число a на 2 (целочисленно): f(a//2, b)
    # Складываем количество путей от обоих вариантов
    return f(a - 1, b) + f(a // 2, b)

# Вычисляем произведение двух значений:
# 1. Количество способов преобразовать число 40 в число 16
# 2. Количество способов преобразовать число 16 в число 6
print(f(40, 16) * f(16, 6))


