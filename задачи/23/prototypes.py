# У исполнителя имеются три команды, которые обозначены латинскими буквами:

# A. Прибавь 1
# B. Прибавь 5
# C. Умножь на 3

# Программа для исполнителя – это последовательность команд. Сколько существует программ, для которых при исходном числе 2 результатом является 49, при этом траектория вычислений содержит 18 или 30, и не содержит чисел 28 и 36?

def f(a, b):
    # Базовый случай: достигли целевого числа - нашли один путь
    if a == b:
        return 1
    # Если текущее число больше целевого ИЛИ
    # текущее число равно 28 или 36 (запрещенные числа - "ловушки")
    # то возвращаем 0 (путь невозможен)
    elif a > b or a in [28, 36]:
        return 0
    # Рекурсивно считаем количество путей через три возможные операции:
    # 1. Прибавить 1: f(a+1, b)
    # 2. Прибавить 5: f(a+5, b)
    # 3. Умножить на 3: f(a*3, b)
    # Суммируем количество путей от всех вариантов
    return f(a + 1, b) + f(a + 5, b) + f(a * 3, b)

# Количество путей от 2 до 18, умноженное на количество путей от 18 до 49
# Это пути, которые проходят через число 18
r1 = f(2, 18) * f(18, 49)

# Количество путей от 2 до 30, умноженное на количество путей от 30 до 49
# Это пути, которые проходят через число 30
r2 = f(2, 30) * f(30, 49)

# Количество путей от 2 до 18, умноженное на количество путей от 18 до 30,
# умноженное на количество путей от 30 до 49
# Это пути, которые проходят через оба числа: сначала через 18, потом через 30
r3 = f(2, 18) * f(18, 30) * f(30, 49)

# Вычисляем объединение множеств путей, проходящих через 18 или через 30
# Используем формулу включений-исключений: |A ∪ B| = |A| + |B| - |A ∩ B|
# A - пути через 18, B - пути через 30, A∩B - пути через оба числа
print(r1 + r2 - r3)

