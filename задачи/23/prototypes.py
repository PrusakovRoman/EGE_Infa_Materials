# Программа для исполнителя – это последовательность команд. Сколько существует программ, для которых при исходном числе 106 результатом является 6, при этом траектория вычислений содержит ровно одно из чисел 48 или 61 (но не оба одновременно)?

def f(a, b):
    # Базовый случай: достигли целевого числа - нашли один путь
    if a == b:
        return 1
    # Если текущее число меньше целевого, дальше уменьшать нельзя
    # возвращаем 0 (путь невозможен)
    if a < b:
        return 0
    # Рекурсивно считаем количество путей через три возможные операции:
    # 1. Вычесть 1: f(a-1, b)
    # 2. Целочисленно разделить на 2: f(a//2, b)
    # 3. Целочисленно разделить на 3: f(a//3, b)
    # Суммируем количество путей от всех вариантов
    return f(a - 1, b) + f(a // 2, b) + f(a // 3, b)

# Количество путей от 106 до 61, умноженное на количество путей от 61 до 6
# Это пути, которые проходят через число 61
r1 = f(106, 61) * f(61, 6)

# Количество путей от 106 до 48, умноженное на количество путей от 48 до 6
# Это пути, которые проходят через число 48
r2 = f(106, 48) * f(48, 6)

# Количество путей от 106 до 61, умноженное на количество путей от 61 до 48,
# умноженное на количество путей от 48 до 6
# Это пути, которые проходят через оба числа: сначала через 61, потом через 48
r3 = f(106, 61) * f(61, 48) * f(48, 6)

# Вычисляем объединение множеств путей, проходящих через 61 или через 48
# Используем формулу: |A ∪ B| = |A| + |B| - 2*|A ∩ B|
# A - пути через 61, B - пути через 48, A∩B - пути через оба числа
# Вычитаем 2*r3, потому что пути через оба числа посчитаны дважды (в r1 и r2)
print(r1 + r2 - 2 * r3)